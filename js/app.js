function updateOpenGraphMetaTags(gallery) {
  if (!gallery) return;

  const tabTitle = gallery.pageTitle || gallery.tabTitle || (gallery.albumTitle ? `${gallery.albumTitle} - 客戶交圖專區 | Wei's Portfolio` : "客戶交圖專區");
  document.title = tabTitle;

  const title = gallery.ogTitle || (gallery.albumTitle ? `【${gallery.albumTitle}】相片全輯與線上交圖` : "客戶交圖專區");
  const description = gallery.ogDescription || `歡迎存取 ${gallery.clientName || '貴賓'} 的 ${gallery.albumTitle || '相片全輯'}。請輸入專屬密碼進行高畫質相片全輯下載與單張預覽。`;
  
  let image = gallery.ogImage || gallery.ogCover;
  if (!image && gallery.baseUrl && gallery.photos && gallery.photos.length > 0) {
    const firstPhoto = typeof gallery.photos[0] === 'string' ? gallery.photos[0] : (gallery.photos[0].filename || '');
    image = gallery.baseUrl + firstPhoto;
  }
  if (!image) {
    image = "https://weipic.github.io/assets/images/og_cover.jpg";
  }
  image = getEncodedPhotoUrl(image);

  setMetaTagContent('property', 'og:title', title);
  setMetaTagContent('name', 'twitter:title', title);
  setMetaTagContent('name', 'title', title);

  setMetaTagContent('property', 'og:description', description);
  setMetaTagContent('name', 'twitter:description', description);
  setMetaTagContent('name', 'description', description);

  setMetaTagContent('property', 'og:image', image);
  setMetaTagContent('property', 'og:image:secure_url', image);
  setMetaTagContent('property', 'og:image:type', 'image/jpeg');
  setMetaTagContent('name', 'twitter:image', image);
}

function setMetaTagContent(attrName, attrValue, content) {
  let element = document.querySelector(`meta[${attrName}="${attrValue}"]`);
  if (!element) {
    element = document.createElement('meta');
    element.setAttribute(attrName, attrValue);
    document.head.appendChild(element);
  }
  element.setAttribute('content', content);
}

function normalizeSlug(str) {
  return (str || '').toString().toLowerCase().replace(/[^a-z0-9\u4e00-\u9fa5]/g, '');
}

function findGalleryByIdOrSlug(targetStr) {
  if (!targetStr) return null;
  const list = getGalleriesList();
  const targetNorm = normalizeSlug(targetStr);
  if (!targetNorm) return null;

  return list.find(g => {
    const idNorm = normalizeSlug(g.id);
    const zipNorm = normalizeSlug(g.zipFilename);
    const titleNorm = normalizeSlug(g.albumTitle);

    return (idNorm && (idNorm === targetNorm || idNorm.includes(targetNorm) || targetNorm.includes(idNorm))) ||
           (zipNorm && zipNorm === targetNorm) ||
           (titleNorm && titleNorm === targetNorm);
  }) || null;
}

function getAlbumIdFromUrl() {
  const urlParams = new URLSearchParams(window.location.search);
  const paramId = urlParams.get('id') || urlParams.get('album');
  if (paramId) return paramId.trim();

  const path = window.location.pathname || '';
  const segments = path.split('/').filter(Boolean);
  if (segments.length > 0) {
    let lastSegment = segments[segments.length - 1];
    if (lastSegment.toLowerCase().endsWith('.html')) {
      lastSegment = lastSegment.slice(0, -5);
    }
    const systemPages = ['index', 'commercial', 'portrait', 'concert', 'event', 'sports', 'graduation', 'landscape', 'contact', 'download', '404'];
    if (!systemPages.includes(lastSegment.toLowerCase())) {
      return decodeURIComponent(lastSegment.trim());
    }
  }

  return null;
}

function matchesPassword(gallery, pass) {
  if (!gallery || !pass) return false;
  const trimmed = pass.trim();
  const rawPass = gallery.password;
  let isMatch = false;

  if (rawPass) {
    if (Array.isArray(rawPass)) {
      isMatch = rawPass.some(p => (p || '').toString().trim() === trimmed);
    } else {
      const str = rawPass.toString();
      const list = str.split(/[,|/]/).map(p => p.trim());
      isMatch = list.includes(trimmed);
    }
  }

  return isMatch;
}

const WORKER_API_ENDPOINT = (window.PORTFOLIO_DATA && window.PORTFOLIO_DATA.workerApiEndpoint) || "https://weipic-api.weipic2023.workers.dev/";

async function verifyPasswordWithWorker(albumId, password) {
  const trimmed = (password || '').trim();
  if (!trimmed) return null;

  try {
    const res = await fetch(WORKER_API_ENDPOINT, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        albumId: albumId || '',
        password: trimmed
      })
    });

    if (res.ok) {
      const data = await res.json();
      if (data && data.success && data.gallery) {
        return data.gallery;
      }
    }
  } catch (err) {
    console.error('Worker API verify error:', err);
  }

  return null;
}

function findGalleryByPassword(pass, targetAlbumId = null) {
  const list = getGalleriesList();
  const trimmed = (pass || '').trim();
  if (!trimmed) return null;

  const urlId = targetAlbumId || getAlbumIdFromUrl();

  if (urlId) {
    const matchedById = findGalleryByIdOrSlug(urlId);
    if (matchedById) {
      if (matchesPassword(matchedById, trimmed)) {
        return matchedById;
      }
    }
    return null;
  }

  return list.find(g => matchesPassword(g, trimmed)) || null;
}

function getAlbumTitleForId(targetId, targetGallery) {
  if (targetGallery && targetGallery.albumTitle) {
    return targetGallery.albumTitle;
  }

  if (targetId) {
    const savedId = sessionStorage.getItem('wei_last_album_id');
    const savedTitle = sessionStorage.getItem('wei_last_album_title');
    if (savedId && savedTitle && savedId.toLowerCase() === targetId.toLowerCase()) {
      return savedTitle;
    }
  }

  const currentPath = window.location.pathname || '';
  const isMainDownloadPage = currentPath.toLowerCase().endsWith('/download.html') ||
                             currentPath.toLowerCase().endsWith('/download') ||
                             currentPath.toLowerCase().endsWith('/404.html') ||
                             currentPath.toLowerCase().endsWith('/404');

  if (!isMainDownloadPage) {
    const existingHeader = document.getElementById('password-header-title');
    if (existingHeader && existingHeader.textContent.trim() && !existingHeader.textContent.includes('客戶交圖')) {
      return existingHeader.textContent.trim();
    }

    const metaOgTitle = document.querySelector('meta[property="og:title"]')?.getAttribute('content');
    if (metaOgTitle && !metaOgTitle.includes('客戶交圖')) {
      let cleaned = metaOgTitle.replace(/[\｜\|]\s*Wei'?s\s*Portfolio.*/i, '').trim();
      cleaned = cleaned.replace(/^【\s*|\s*】$/g, '').trim();
      if (cleaned && cleaned !== "Wei's Portfolio" && !cleaned.includes('客戶交圖')) return cleaned;
    }

    const pageTitle = document.title;
    if (pageTitle && !pageTitle.includes('客戶交圖')) {
      let cleaned = pageTitle.replace(/[\｜\|]\s*Wei'?s\s*Portfolio.*/i, '').trim();
      cleaned = cleaned.replace(/^【\s*|\s*】$/g, '').trim();
      if (cleaned && cleaned !== "Wei's Portfolio" && !cleaned.includes('客戶交圖')) return cleaned;
    }
  }

  if (targetId) {
    return decodeURIComponent(targetId);
  }

  return "客戶交圖專區";
}

