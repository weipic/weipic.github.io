// Toggle Collaborations Unfold/Fold Function
function toggleCollaborations() {
  const wrapper = document.getElementById('collab-grid-wrapper');
  const overlay = document.getElementById('collab-gradient-overlay');
  const btnText = document.getElementById('collab-btn-text');
  const btnIcon = document.getElementById('collab-btn-icon');

  if (!wrapper) return;

  isCollabExpanded = !isCollabExpanded;
  trackGAEvent(isCollabExpanded ? '展開合作經歷' : '收合合作經歷');

  if (isCollabExpanded) {
    wrapper.style.maxHeight = (wrapper.scrollHeight + 40) + 'px';
    if (overlay) overlay.classList.add('opacity-0');
    if (btnText) btnText.innerText = '收起經歷';
    if (btnIcon) btnIcon.classList.add('rotate-180');
  } else {
    wrapper.style.maxHeight = '340px';
    if (overlay) overlay.classList.remove('opacity-0');
    if (btnText) {
      const count = window.PORTFOLIO_DATA?.collaborations?.length || '';
      btnText.innerText = count ? `顯示更多經歷 (${count})` : '顯示更多經歷';
    }
    if (btnIcon) btnIcon.classList.remove('rotate-180');
    
    // Smooth scroll back to collaborations section top
    const collabSection = document.getElementById('collaborations-section');
    if (collabSection) {
      collabSection.scrollIntoView({ behavior: 'smooth' });
    }
  }
}

