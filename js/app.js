// Helper: Send GA4 Custom Event with Chinese Name
function trackGAEvent(eventName, eventParams = {}) {
  try {
    if (typeof window.gtag === 'function') {
      window.gtag('event', eventName, eventParams);
    }
  } catch (err) {
    console.warn('GA tracking error:', err);
  }
}

