window.setLanguage = function(langCode) {
  const currentDomain = window.location.hostname;
  
  if (langCode === 'zh-TW') {
    document.cookie = "googtrans=; expires=Thu, 01 Jan 1970 00:00:00 UTC; path=/;";
    document.cookie = "googtrans=/zh-TW/zh-TW; path=/;";
    if (currentDomain) {
      document.cookie = `googtrans=; expires=Thu, 01 Jan 1970 00:00:00 UTC; domain=${currentDomain}; path=/;`;
      document.cookie = `googtrans=; expires=Thu, 01 Jan 1970 00:00:00 UTC; domain=.${currentDomain}; path=/;`;
    }
  } else {
    const val = `/zh-TW/${langCode}`;
    document.cookie = `googtrans=${val}; path=/;`;
    if (currentDomain) {
      document.cookie = `googtrans=${val}; domain=${currentDomain}; path=/;`;
      document.cookie = `googtrans=${val}; domain=.${currentDomain}; path=/;`;
    }
  }
  
  localStorage.setItem('selected_lang', langCode);

  const triggerChange = () => {
    const selectElem = document.querySelector('.goog-te-combo');
    if (selectElem) {
      selectElem.value = langCode;
      selectElem.dispatchEvent(new Event('change'));
      return true;
    }
    return false;
  };

  if (!triggerChange()) {
    setTimeout(triggerChange, 300);
    setTimeout(triggerChange, 800);
  }

  updateLanguageUIState(langCode);
  window.location.reload();
};

function updateLanguageUIState(langCode) {
  const activeLang = langCode || localStorage.getItem('selected_lang') || 'zh-TW';
  const allLangBtns = document.querySelectorAll('.lang-opt-btn');
  
  allLangBtns.forEach(btn => {
    const targetLang = btn.getAttribute('data-lang');
    if (targetLang === activeLang) {
      btn.classList.add('text-amber-400', 'font-semibold');
      btn.classList.remove('text-gray-300');
    } else {
      btn.classList.remove('text-amber-400', 'font-semibold');
      btn.classList.add('text-gray-300');
    }
  });
}

function initLanguageSelector() {
  if (!document.getElementById('google_translate_element')) {
    const div = document.createElement('div');
    div.id = 'google_translate_element';
    div.style.display = 'none';
    document.body.appendChild(div);
  }

  if (!document.getElementById('google-translate-script')) {
    const script = document.createElement('script');
    script.id = 'google-translate-script';
    script.src = 'https://translate.google.com/translate_a/element.js?cb=googleTranslateElementInit';
    document.body.appendChild(script);
  }

  const langBtn = document.getElementById('lang-btn');
  const langMenu = document.getElementById('lang-dropdown-menu');

  if (langBtn && langMenu) {
    langBtn.addEventListener('click', (e) => {
      e.stopPropagation();
      langMenu.classList.toggle('show');
    });

    document.addEventListener('click', (e) => {
      if (!langBtn.contains(e.target) && !langMenu.contains(e.target)) {
        langMenu.classList.remove('show');
      }
    });
  }

  const storedLang = localStorage.getItem('selected_lang') || 'zh-TW';
  updateLanguageUIState(storedLang);
}

// --------------------------------------------------------------------
// Image Protection: Prevent right-click, dragging & long-press download
// --------------------------------------------------------------------
function initProtectImages() {
  // 1. Prevent right-click context menu (Desktop right-click & Mobile long-press)
  document.addEventListener('contextmenu', (e) => {
    if (e.target.tagName === 'IMG' || e.target.closest('img') || e.target.closest('.image-hover-zoom') || e.target.closest('#lightbox-modal')) {
      e.preventDefault();
      return false;
    }
  }, { capture: true });

  // 2. Prevent dragging images to save or open in new tab
  document.addEventListener('dragstart', (e) => {
    if (e.target.tagName === 'IMG' || e.target.closest('img') || e.target.closest('.image-hover-zoom') || e.target.closest('#lightbox-modal')) {
      e.preventDefault();
      return false;
    }
  }, { capture: true });

  // 3. Ensure draggable="false" on all img elements (current & dynamically appended)
  const applyNoDrag = (rootNode = document) => {
    if (!rootNode) return;
    if (rootNode.tagName === 'IMG') {
      rootNode.setAttribute('draggable', 'false');
    }
    if (rootNode.querySelectorAll) {
      rootNode.querySelectorAll('img').forEach(img => {
        img.setAttribute('draggable', 'false');
      });
    }
  };

  applyNoDrag(document);

  // Observer to catch any dynamically added image elements (like Lightbox modal)
  const observer = new MutationObserver((mutations) => {
    mutations.forEach(mutation => {
      mutation.addedNodes.forEach(node => {
        if (node.nodeType === 1) {
          applyNoDrag(node);
        }
      });
    });
  });

  observer.observe(document.body || document.documentElement, { childList: true, subtree: true });
}

