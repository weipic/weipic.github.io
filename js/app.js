async function downloadSinglePhoto(photoUrl, filename, btnEl = null) {
  trackGAEvent('下載單張照片', { '照片網址': photoUrl });
  
  const cleanUrl = getEncodedPhotoUrl(photoUrl);

  let originalHtml = '';
  if (btnEl) {
    originalHtml = btnEl.innerHTML;
    btnEl.disabled = true;
    btnEl.classList.add('opacity-75', 'cursor-wait');
    btnEl.innerHTML = `
      <svg class="w-4 h-4 animate-spin inline-block" fill="none" viewBox="0 0 24 24">
        <circle class="opacity-25" cx="12" cy="12" r="10" stroke="currentColor" stroke-width="4"></circle>
        <path class="opacity-75" fill="currentColor" d="M4 12a8 8 0 018-8V0C5.373 0 0 5.373 0 12h4zm2 5.291A7.962 7.962 0 014 12H0c0 3.042 1.135 5.824 3 7.938l3-2.647z"></path>
      </svg>
      <span>下載中...</span>
    `;
  }

  const resetBtn = () => {
    if (btnEl) {
      btnEl.disabled = false;
      btnEl.classList.remove('opacity-75', 'cursor-wait');
      btnEl.innerHTML = originalHtml;
    }
  };

  const isMobile = /Android|webOS|iPhone|iPad|iPod|BlackBerry|IEMobile|Opera Mini/i.test(navigator.userAgent) || (navigator.platform === 'MacIntel' && navigator.maxTouchPoints > 1);

  // Synchronously prepare a window popup placeholder to bypass pop-up blockers if fetch fails or fallback is needed
  let popupWindow = null;

  let fetchedBlob = null;
  let retries = 3;

  while (retries > 0 && !fetchedBlob) {
    try {
      const fetchUrl = cleanUrl + (cleanUrl.includes('?') ? '&dl=1' : '?dl=1');
      const resp = await fetch(fetchUrl, { mode: 'cors' });
      if (!resp.ok) throw new Error(`HTTP ${resp.status}`);
      fetchedBlob = await resp.blob();
    } catch (err) {
      retries--;
      if (retries > 0) {
        await new Promise(r => setTimeout(r, 300));
      } else {
        console.error(`Failed to fetch photo ${cleanUrl} after retries:`, err);
      }
    }
  }

  if (fetchedBlob) {
    const safeFilename = filename || photoUrl.split('/').pop() || 'photo.jpg';
    const mimeType = fetchedBlob.type || 'image/jpeg';

    // 📱 Mobile Web Share API support (iOS 15+ & Android native share to Photos/Files)
    if (isMobile && navigator.canShare) {
      try {
        const file = new File([fetchedBlob], safeFilename, { type: mimeType });
        if (navigator.canShare({ files: [file] })) {
          await navigator.share({
            files: [file],
            title: safeFilename
          });
          resetBtn();
          return;
        }
      } catch (shareErr) {
        if (shareErr.name !== 'AbortError') {
          console.warn('Web Share API error:', shareErr);
        } else {
          // User cancelled share dialog
          resetBtn();
          return;
        }
      }
    }

    try {
      const blobUrl = URL.createObjectURL(fetchedBlob);
      const a = document.createElement('a');
      a.href = blobUrl;
      a.download = safeFilename;
      a.target = '_blank';
      a.style.display = 'none';
      document.body.appendChild(a);
      a.click();

      if (isMobile) {
        // Mobile browser fallback if a.click() doesn't prompt save
        window.location.href = blobUrl;
      }

      setTimeout(() => {
        if (a.parentNode) a.parentNode.removeChild(a);
        URL.revokeObjectURL(blobUrl);
      }, 10000);
    } catch (err) {
      console.error('Blob URL download trigger error:', err);
      window.open(cleanUrl, '_blank');
    }
  } else {
    console.warn('Single photo fetch failed (likely CORS or Network), navigating directly to image URL.');
    // Direct open fallback
    const windowTarget = isMobile ? '_self' : '_blank';
    window.open(cleanUrl, windowTarget);
  }

  resetBtn();
}

function openDownloadLightbox(index) {
  const activeCfg = currentActiveConfig || (getGalleriesList()[0] || {});
  const photos = (activeCfg && (activeCfg.photosList || activeCfg.photos)) || currentDownloadPhotos || [];
  if (!photos || !photos.length) return;
  currentDownloadPhotoIndex = index;

  const modal = document.getElementById('download-lightbox-modal');
  const imgEl = document.getElementById('download-lightbox-img');
  const counterEl = document.getElementById('download-lightbox-counter');
  const downloadBtn = document.getElementById('download-lightbox-dl-btn');

  if (!modal || !imgEl) return;

  const rawPhoto = photos[index];
  const norm = normalizePhotoItem(rawPhoto, activeCfg);
  const displayUrl = getEncodedPhotoUrl(norm.displayUrl);
  const originalUrl = getEncodedPhotoUrl(norm.originalUrl);
  const filename = norm.filename || `photo_${index + 1}.jpg`;

  imgEl.src = displayUrl;
  if (displayUrl !== originalUrl) {
    const highResImg = new Image();
    highResImg.src = originalUrl;
    highResImg.onload = () => {
      if (currentDownloadPhotoIndex === index) {
        imgEl.src = originalUrl;
      }
    };
  }

  imgEl.alt = norm.title || `${index + 1}`;

  if (counterEl) {
    counterEl.textContent = `${index + 1} / ${photos.length}`;
  }

  if (downloadBtn) {
    downloadBtn.innerHTML = `
      <svg class="w-5 h-5" fill="none" stroke="currentColor" viewBox="0 0 24 24"><path stroke-linecap="round" stroke-linejoin="round" stroke-width="2" d="M4 16v1a3 3 0 003 3h10a3 3 0 003-3v-1m-4-4l-4 4m0 0l-4-4m4 4V4"/></svg>
      <span>Download</span>
    `;
    downloadBtn.onclick = (e) => downloadSinglePhoto(originalUrl, filename, e ? (e.currentTarget || e.target) : downloadBtn);
  }

  modal.classList.remove('hidden');
  modal.classList.add('flex');

  document.removeEventListener('keydown', handleDownloadLightboxKeys);
  document.addEventListener('keydown', handleDownloadLightboxKeys);
}

function closeDownloadLightbox() {
  const modal = document.getElementById('download-lightbox-modal');
  if (modal) {
    modal.classList.add('hidden');
    modal.classList.remove('flex');
  }
  document.removeEventListener('keydown', handleDownloadLightboxKeys);
}

function handleDownloadLightboxKeys(e) {
  if (e.key === 'Escape') {
    closeDownloadLightbox();
  } else if (e.key === 'ArrowLeft') {
    navigateDownloadLightbox(-1);
  } else if (e.key === 'ArrowRight') {
    navigateDownloadLightbox(1);
  }
}

function navigateDownloadLightbox(dir) {
  if (!currentDownloadPhotos || !currentDownloadPhotos.length) return;
  let newIndex = currentDownloadPhotoIndex + dir;
  if (newIndex < 0) newIndex = currentDownloadPhotos.length - 1;
  if (newIndex >= currentDownloadPhotos.length) newIndex = 0;
  openDownloadLightbox(newIndex);
}


