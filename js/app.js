/* ====================================================================
   📱 MOBILE TOUCH HOVER & TAP INTERACTION LOGIC
   ==================================================================== */
function initMobileTouchHover() {
  let activeCard = null;
  let startX = 0;
  let startY = 0;
  let isScrolling = false;
  let fadeTimeout = null;

  function clearActiveCard() {
    if (activeCard) {
      activeCard.classList.remove('touch-active');
      activeCard = null;
    }
  }

  function getCardFromTouch(touch) {
    if (!touch) return null;
    const target = document.elementFromPoint(touch.clientX, touch.clientY);
    return target ? target.closest('.luxury-card, .gallery-item') : null;
  }

  document.addEventListener('touchstart', (e) => {
    if (e.touches.length !== 1) return;
    const touch = e.touches[0];
    startX = touch.clientX;
    startY = touch.clientY;
    isScrolling = false;

    if (fadeTimeout) {
      clearTimeout(fadeTimeout);
      fadeTimeout = null;
    }

    const card = getCardFromTouch(touch);
    if (card) {
      if (activeCard && activeCard !== card) {
        activeCard.classList.remove('touch-active');
      }
      activeCard = card;
      activeCard.classList.add('touch-active');
    }
  }, { passive: true });

  document.addEventListener('touchmove', (e) => {
    if (e.touches.length !== 1) return;
    const touch = e.touches[0];
    const dx = Math.abs(touch.clientX - startX);
    const dy = Math.abs(touch.clientY - startY);

    if (dx > 8 || dy > 8) {
      isScrolling = true;
    }

    const card = getCardFromTouch(touch);
    if (card) {
      if (activeCard && activeCard !== card) {
        activeCard.classList.remove('touch-active');
      }
      activeCard = card;
      activeCard.classList.add('touch-active');
    } else {
      if (activeCard) {
        activeCard.classList.remove('touch-active');
        activeCard = null;
      }
    }
  }, { passive: true });

  document.addEventListener('touchend', () => {
    if (isScrolling) {
      fadeTimeout = setTimeout(() => {
        clearActiveCard();
      }, 400);
    } else {
      fadeTimeout = setTimeout(() => {
        clearActiveCard();
      }, 300);
    }
  }, { passive: true });

  document.addEventListener('touchcancel', () => {
    clearActiveCard();
  }, { passive: true });

  document.addEventListener('click', (e) => {
    if (isScrolling) {
      e.preventDefault();
      e.stopPropagation();
      isScrolling = false;
    }
  }, true);
}

