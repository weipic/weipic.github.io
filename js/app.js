window.setLanguage = function(langCode) {
  const currentDomain = window.location.hostname;

  trackGAEvent('切換網站語言', {
    '目標語言': langCode
  });
  
  if (langCode === 'zh-TW') {
    document.cookie = "googtrans=; expires=Thu, 01 Jan 1970 00:00:00 UTC; path=/;";
    document.cookie = "googtrans=/zh-TW/zh-TW; path=/;";
    if (currentDomain) {
      document.cookie = `googtrans=; expires=Thu, 01 Jan 1970 00:00:00 UTC; domain=${currentDomain}; path=/;`;
      document.cookie = `googtrans=; expires=Thu, 01 Jan 1970 00:00:00 UTC; domain=.${currentDomain}; path=/;`;
    }
  } else {
    const val = `/zh-TW/${langCode}`;
    document.cookie = `googtrans=${val}; path=/;`;
    if (currentDomain) {
      document.cookie = `googtrans=${val}; domain=${currentDomain}; path=/;`;
      document.cookie = `googtrans=${val}; domain=.${currentDomain}; path=/;`;
    }
  }
  
  localStorage.setItem('selected_lang', langCode);

  const triggerChange = () => {
    const selectElem = document.querySelector('.goog-te-combo');
    if (selectElem) {
      selectElem.value = langCode;
      selectElem.dispatchEvent(new Event('change'));
      return true;
    }
    return false;
  };

  if (!triggerChange()) {
    setTimeout(triggerChange, 300);
    setTimeout(triggerChange, 800);
  }

  updateLanguageUIState(langCode);
  window.location.reload();
};

