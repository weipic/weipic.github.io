let isZippingInProcess = false;

async function downloadAllPhotosAsZip(config) {
  if (isZippingInProcess) return;
  const zipBtnEl = document.getElementById('download-zip-btn');
  const photos = config.photos || [];

  if (!photos.length) {
    alert('相簿中目前尚無可下載的照片！');
    return;
  }

  if (typeof JSZip === 'undefined') {
    console.error('JSZip is not loaded');
    alert('動態壓縮元件載入中，請稍後再試。');
    return;
  }

  isZippingInProcess = true;
  const originalBtnText = zipBtnEl ? zipBtnEl.innerHTML : '';

  try {
    const zip = new JSZip();
    const baseUrl = config.baseUrl || '';
    const zipDownloadName = getZipDownloadFilename(config);

    let completedCount = 0;
    const totalCount = photos.length;

    if (zipBtnEl) {
      zipBtnEl.innerHTML = `
        <svg class="w-5 h-5 animate-spin" fill="none" viewBox="0 0 24 24">
          <circle class="opacity-25" cx="12" cy="12" r="10" stroke="currentColor" stroke-width="4"></circle>
          <path class="opacity-75" fill="currentColor" d="M4 12a8 8 0 018-8V0C5.373 0 0 5.373 0 12h4zm2 5.291A7.962 7.962 0 014 12H0c0 3.042 1.135 5.824 3 7.938l3-2.647z"></path>
        </svg>
        <span>相片讀取中 (0/${totalCount})...</span>
      `;
    }

    const CONCURRENCY_LIMIT = 3;
    const queue = photos.map((p, i) => ({ photo: p, idx: i }));
    let addedCount = 0;

    const downloadWorker = async () => {
      while (queue.length > 0) {
        const item = queue.shift();
        if (!item) break;

        const rawPhoto = item.photo;
        const idx = item.idx;
        const photo = typeof rawPhoto === 'string' ? { filename: rawPhoto } : rawPhoto;
        const rawImgUrl = photo.url || (baseUrl + (photo.filename || ''));
        const imgUrl = getEncodedPhotoUrl(rawImgUrl);
        const defaultFilename = `photo_${String(idx + 1).padStart(3, '0')}.jpg`;
        const filename = photo.filename || defaultFilename;

        let fetchedBuffer = null;
        let retries = 5;

        while (retries > 0 && !fetchedBuffer) {
          try {
            const fetchUrl = imgUrl + (imgUrl.includes('?') ? '&dl=1' : '?dl=1');
            const resp = await fetch(fetchUrl, { mode: 'cors' });
            if (!resp.ok) throw new Error(`HTTP ${resp.status}`);
            fetchedBuffer = await resp.arrayBuffer();
          } catch (err) {
            retries--;
            if (retries > 0) {
              await new Promise(r => setTimeout(r, 600 * (6 - retries)));
            } else {
              console.error(`Failed to download ${imgUrl} after 5 retries:`, err);
            }
          }
        }

        if (fetchedBuffer) {
          // 💡 直接放置於 ZIP 根目錄，避免解壓縮後出現「雙重資料夾」夾中資料夾的情況
          zip.file(filename, fetchedBuffer);
          addedCount++;
        }

        completedCount++;
        if (zipBtnEl) {
          zipBtnEl.innerHTML = `
            <svg class="w-5 h-5 animate-spin" fill="none" viewBox="0 0 24 24">
              <circle class="opacity-25" cx="12" cy="12" r="10" stroke="currentColor" stroke-width="4"></circle>
              <path class="opacity-75" fill="currentColor" d="M4 12a8 8 0 018-8V0C5.373 0 0 5.373 0 12h4zm2 5.291A7.962 7.962 0 014 12H0c0 3.042 1.135 5.824 3 7.938l3-2.647z"></path>
            </svg>
            <span>相片打包中 (${addedCount}/${totalCount})...</span>
          `;
        }
      }
    };

    const workers = Array.from({ length: Math.min(CONCURRENCY_LIMIT, totalCount) }, () => downloadWorker());
    await Promise.all(workers);

    if (addedCount < totalCount) {
      console.warn(`Only ${addedCount} out of ${totalCount} photos were packed.`);
    }

    if (zipBtnEl) {
      zipBtnEl.innerHTML = `
        <svg class="w-5 h-5 animate-spin" fill="none" viewBox="0 0 24 24">
          <circle class="opacity-25" cx="12" cy="12" r="10" stroke="currentColor" stroke-width="4"></circle>
          <path class="opacity-75" fill="currentColor" d="M4 12a8 8 0 018-8V0C5.373 0 0 5.373 0 12h4zm2 5.291A7.962 7.962 0 014 12H0c0 3.042 1.135 5.824 3 7.938l3-2.647z"></path>
        </svg>
        <span>壓縮檔生成中...</span>
      `;
    }

    const content = await zip.generateAsync({ type: 'blob', compression: 'STORE' }, (metadata) => {
      if (zipBtnEl) {
        zipBtnEl.innerHTML = `
          <svg class="w-5 h-5 animate-spin" fill="none" viewBox="0 0 24 24">
            <circle class="opacity-25" cx="12" cy="12" r="10" stroke="currentColor" stroke-width="4"></circle>
            <path class="opacity-75" fill="currentColor" d="M4 12a8 8 0 018-8V0C5.373 0 0 5.373 0 12h4zm2 5.291A7.962 7.962 0 014 12H0c0 3.042 1.135 5.824 3 7.938l3-2.647z"></path>
          </svg>
          <span>生成 ZIP (${Math.round(metadata.percent)}%)...</span>
        `;
      }
    });

    const blobUrl = URL.createObjectURL(content);
    const link = document.createElement('a');
    link.href = blobUrl;
    link.download = zipDownloadName;
    link.target = '_blank';
    document.body.appendChild(link);
    link.click();

    const isMobile = /Android|webOS|iPhone|iPad|iPod|BlackBerry|IEMobile|Opera Mini/i.test(navigator.userAgent) || (navigator.platform === 'MacIntel' && navigator.maxTouchPoints > 1);
    if (isMobile) {
      // Direct navigation trigger on mobile to prevent pop-up blocker from suppressing the download
      window.location.href = blobUrl;
    }

    setTimeout(() => {
      if (link.parentNode) link.parentNode.removeChild(link);
      URL.revokeObjectURL(blobUrl);
    }, 15000);

    trackGAEvent('一鍵動態打包下載全輯ZIP', { '相簿標題': config.albumTitle, '相片張數': totalCount });
  } catch (err) {
    console.error('ZIP generation error:', err);
    alert('自動打包 ZIP 失敗，請重試或點擊單張下載。');
  } finally {
    isZippingInProcess = false;
    if (zipBtnEl && originalBtnText) {
      zipBtnEl.innerHTML = originalBtnText;
    }
  }
}

function normalizePhotoItem(rawItem, config) {
  const item = typeof rawItem === 'string' ? { filename: rawItem } : (rawItem || {});
  const cfg = config || {};
  const baseUrl = item.baseUrl || cfg.baseUrl || '';
  const filename = item.filename || (typeof rawItem === 'string' ? rawItem : '');

  const originalUrl = item.originalUrl || item.url || (baseUrl.endsWith('/') ? (baseUrl + filename) : (baseUrl + '/' + filename));

  let displayUrl = item.displayUrl || item.previewUrl || item.thumbUrl;
  if (!displayUrl) {
    const previewBaseUrl = item.previewBaseUrl || cfg.previewBaseUrl || cfg.thumbBaseUrl;
    if (previewBaseUrl) {
      let fullPreviewBase = previewBaseUrl;
      if (!previewBaseUrl.startsWith('http://') && !previewBaseUrl.startsWith('https://') && !previewBaseUrl.startsWith('/')) {
        fullPreviewBase = baseUrl.endsWith('/') ? (baseUrl + previewBaseUrl) : (baseUrl + '/' + previewBaseUrl);
      }
      if (!fullPreviewBase.endsWith('/')) {
        fullPreviewBase += '/';
      }
      displayUrl = fullPreviewBase + filename;
    } else if (originalUrl && (originalUrl.startsWith('http://') || originalUrl.startsWith('https://'))) {
      try {
        const origin = new URL(originalUrl).origin;
        displayUrl = `${origin}/cdn-cgi/image/width=800,quality=80,format=auto/${originalUrl}`;
      } catch (e) {
        displayUrl = `/cdn-cgi/image/width=800,quality=80,format=auto/${originalUrl}`;
      }
    } else {
      displayUrl = originalUrl;
    }
  }

  return {
    filename: filename,
    originalUrl: originalUrl,
    displayUrl: displayUrl,
    title: item.title || filename
  };
}

