async function handleFormSubmit(e) {
  e.preventDefault();
  
  const submitBtn = document.getElementById('contact-submit-btn');
  const statusMsg = document.getElementById('form-status-msg');
  const form = e.target;

  const name = document.getElementById('contact-name').value;
  const email = document.getElementById('contact-email').value;
  const category = document.getElementById('contact-category').value;
  const message = document.getElementById('contact-message').value;

  if (submitBtn) {
    submitBtn.disabled = true;
    submitBtn.innerHTML = `
      <svg class="animate-spin h-4 w-4 text-black" xmlns="http://www.w3.org/2000/svg" fill="none" viewBox="0 0 24 24">
        <circle class="opacity-25" cx="12" cy="12" r="10" stroke="currentColor" stroke-width="4"></circle>
        <path class="opacity-75" fill="currentColor" d="M4 12a8 8 0 018-8V0C5.373 0 0 5.373 0 12h4zm2 5.291A7.962 7.962 0 014 12H0c0 3.042 1.135 5.824 3 7.938l3-2.647z"></path>
      </svg>
      <span>傳送中...</span>
    `;
  }

  try {
    const response = await fetch('https://formsubmit.co/ajax/weipic2023@gmail.com', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'Accept': 'application/json'
      },
      body: JSON.stringify({
        _subject: `【Wei's Portfolio】新攝影預約詢問 - ${name}`,
        姓名: name,
        電子信箱: email,
        預約類別: category,
        需求與細節: message
      })
    });

    const data = await response.json();

    if (response.ok || data.success === "true") {
      if (statusMsg) {
        statusMsg.className = 'text-xs py-3 px-4 rounded-lg bg-emerald-500/20 border border-emerald-500/40 text-emerald-300 font-medium block';
        statusMsg.innerText = '✅ 預約訊息已成功送出！將會於 24 小時內與您聯繫。';
      }
      trackGAEvent('送出聯絡表單', {
        '預約類別': category,
        '聯絡人姓名': name
      });
      form.reset();
    } else {
      throw new Error(data.message || '發送失敗');
    }
  } catch (error) {
    console.error('Form submission error:', error);
    if (statusMsg) {
      statusMsg.className = 'text-xs py-3 px-4 rounded-lg bg-red-500/20 border border-red-500/40 text-red-300 font-medium block';
      statusMsg.innerText = '⚠️ 送出失敗，請再試一次或直接寄信至 weipic2023@gmail.com';
    }
  } finally {
    if (submitBtn) {
      submitBtn.disabled = false;
      submitBtn.innerHTML = `<span>送出預約表單</span>`;
    }
  }
}

