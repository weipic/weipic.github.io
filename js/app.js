// 4. Multi-photo Project Album & Lightbox Modal with < > Nav Arrows
// --------------------------------------------------------------------
function openProjectAlbum(projectId, categoryId) {
  const data = window.PORTFOLIO_DATA;
  if (!data || !data.galleries) return;

  let project = null;

  if (categoryId && data.galleries[categoryId]) {
    project = data.galleries[categoryId].find(p => p.id === projectId);
  }

  // Auto-search across all categories if categoryId is omitted or not found directly
  if (!project) {
    for (const catKey in data.galleries) {
      const p = data.galleries[catKey].find(item => item.id === projectId);
      if (p) {
        project = p;
        break;
      }
    }
  }

  if (!project) {
    console.warn(`Project with id "${projectId}" not found.`);
    return;
  }

  openCustomProjectModal(project);
}

function openCustomProjectModal(project) {
  const rawPhotos = (project.photos && project.photos.length) ? project.photos : [project.cover || project.image];
  currentAlbumPhotos = rawPhotos.filter(Boolean);
  currentPhotoIndex = 0;

  trackGAEvent('查看作品相本', {
    '相本名稱': project.title || '作品集細節',
    '類別或品牌': project.client || '',
    '年份': project.year || ''
  });

  let modal = document.getElementById('lightbox-modal');
  if (!modal) {
    modal = document.createElement('div');
    modal.id = 'lightbox-modal';
    modal.className = 'fixed inset-0 z-[999] bg-black/95 backdrop-blur-md flex items-center justify-center p-3 sm:p-6 transition-opacity duration-300 opacity-0 pointer-events-none';
    document.body.appendChild(modal);
  }

  renderModalContent(project);

  modal.classList.remove('opacity-0', 'pointer-events-none');
  modal.classList.add('opacity-100');

  window.addEventListener('keydown', handleLightboxKeyboard);
}

